#!/usr/bin/env python3
"""Prepare Comparator inputs and publish a score for an EIP-8200 track."""

from __future__ import annotations

import csv
from dataclasses import dataclass
import hashlib
import json
import os
from pathlib import Path
import re
import sys


HEX_RE = re.compile(r"(?:[0-9a-f]{2})+")


@dataclass(frozen=True)
class Track:
    lean_name: str
    display_name: str
    framed: bool


TRACKS = {
    "modexp": Track("Modexp", "MODEXP", False),
    "ripemd160": Track("Ripemd160", "RIPEMD-160", True),
}


def read_vectors(path: Path) -> tuple[dict[str, int], str]:
    # The scorer has already validated this file and its expected outputs.
    raw = path.read_bytes()
    document = json.loads(raw)
    rows = document["vectors"]
    expected = {row["label"]: len(bytes.fromhex(row["input"].removeprefix("0x"))) for row in rows}
    return expected, hashlib.sha256(raw).hexdigest()


def validate_csv_identity(row: dict[str, str], expected: dict[str, int]) -> None:
    if row["vector"] not in expected or int(row["bytes"]) != expected[row["vector"]]:
        raise ValueError("scorer output does not match the selected suite")


def track_config(name: str) -> Track:
    try:
        return TRACKS[name]
    except KeyError as error:
        raise ValueError(f"unknown track: {name}") from error


def atomic_write(path: Path, contents: str, encoding: str = "utf-8") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(contents, encoding=encoding)
    os.replace(temporary, path)


def read_artifact(path: Path) -> tuple[str, str]:
    try:
        raw = path.read_text(encoding="ascii")
    except (OSError, UnicodeError) as error:
        raise ValueError(f"could not read ASCII bytecode from {path}: {error}") from error

    body = raw[:-1] if raw.endswith("\n") else raw
    if "\n" in body or "\r" in body or HEX_RE.fullmatch(body) is None:
        raise ValueError(
            "bytecode.hex must contain one nonempty line of lowercase byte pairs "
            "without a 0x prefix"
        )
    return raw, body


def render_artifact(track: Track, artifact: str) -> str:
    values = bytes.fromhex(artifact)
    chunks = [values[offset : offset + 64] for offset in range(0, len(values), 64)]
    declarations: list[str] = []
    for index, chunk in enumerate(chunks):
        rows = []
        for offset in range(0, len(chunk), 12):
            row = ", ".join(f"0x{value:02x}" for value in chunk[offset : offset + 12])
            rows.append(f"  {row}")
        declarations.append(
            f"private abbrev artifactChunk{index} : ByteArray := ByteArray.mk #[\n"
            + ",\n".join(rows)
            + "\n]"
        )

    declarations_text = "\n\n".join(declarations)
    expression = " ++\n    ".join(f"artifactChunk{index}" for index in range(len(chunks)))
    return f"""\
/- Generated from the protected submission by scripts/yukon_benchmark.py. -/
import Challenge.{track.lean_name}.Benchmark.Target

namespace Challenge.{track.lean_name}.Benchmark

{declarations_text}

/-- The exact submitted bytes checked by Lean and scored by the EVM runner. -/
abbrev bytecode : ByteArray :=
  {expression}

end Challenge.{track.lean_name}.Benchmark
"""


def render_challenge(track: Track) -> str:
    return f"""\
/- Generated by scripts/yukon_benchmark.py. Do not edit. -/
import Challenge.{track.lean_name}.Benchmark.Artifact

namespace Challenge.{track.lean_name}.Benchmark

theorem candidate : Challenge.{track.lean_name}.Correct bytecode := by
  sorry

end Challenge.{track.lean_name}.Benchmark
"""


def prepare(
    track_name: str,
    submitted: Path,
    trusted: Path,
    artifact_module: Path,
    challenge: Path,
) -> None:
    track = track_config(track_name)
    # The editable artifact is read once. The same bytes feed both the trusted
    # Lean literal and the protected post-verification scorer.
    raw, artifact = read_artifact(submitted)
    atomic_write(trusted, raw, "ascii")
    atomic_write(artifact_module, render_artifact(track, artifact))
    atomic_write(challenge, render_challenge(track))


def parse_framed_csv(
    path: Path,
    expected: dict[str, int],
    expected_fields: list[str] | None = None,
) -> tuple[int, dict[str, object]]:
    clean: dict[str, int] = {}
    dirty: dict[str, int] = {}
    with path.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        expected_fields = expected_fields or ["vector", "bytes", "frame", "status", "gas"]
        if reader.fieldnames != expected_fields:
            raise ValueError(f"unexpected scorer CSV header: {reader.fieldnames}")
        for row in reader:
            validate_csv_identity(row, expected)
            label = row["vector"]
            frame = row["frame"]
            status = row["status"]
            if not status.startswith("ok"):
                raise ValueError(f"scorer rejected {label}/{frame}: {status}")
            try:
                gas = int(row["gas"])
            except (TypeError, ValueError) as error:
                raise ValueError(f"invalid gas for {label}/{frame}: {row['gas']}") from error
            if gas < 0:
                raise ValueError(f"negative gas for {label}/{frame}")
            target = clean if frame == "clean" else dirty if frame == "dirty" else None
            if target is None:
                raise ValueError(f"unexpected scorer frame: {frame}")
            if label in target:
                raise ValueError(f"duplicate scorer row: {label}/{frame}")
            target[label] = gas

    if clean.keys() != expected.keys() or clean.keys() != dirty.keys():
        raise ValueError(
            f"expected {len(expected)} paired vectors, got "
            f"{len(clean)} clean and {len(dirty)} dirty"
        )
    clean_total = sum(clean.values())
    dirty_total = sum(dirty.values())
    return clean_total, {
        "vectors": len(clean),
        "cleanTotalGas": clean_total,
        "dirtyTotalGas": dirty_total,
        "stateIndependentGas": clean_total == dirty_total,
    }


def parse_modexp_csv(path: Path, expected: dict[str, int]) -> tuple[int, dict[str, object]]:
    rows: dict[str, tuple[int, int]] = {}
    with path.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        if reader.fieldnames != ["vector", "bytes", "status", "gas", "precompile"]:
            raise ValueError(f"unexpected scorer CSV header: {reader.fieldnames}")
        for row in reader:
            validate_csv_identity(row, expected)
            label = row["vector"]
            if row["status"] != "ok":
                raise ValueError(f"scorer rejected {label}: {row['status']}")
            if label in rows:
                raise ValueError(f"duplicate scorer row: {label}")
            try:
                gas = int(row["gas"])
                precompile = int(row["precompile"])
            except (TypeError, ValueError) as error:
                raise ValueError(f"invalid gas for {label}") from error
            if gas < 0 or precompile < 0:
                raise ValueError(f"negative gas for {label}")
            rows[label] = (gas, precompile)

    if rows.keys() != expected.keys():
        raise ValueError(f"expected {len(expected)} vectors, got {len(rows)}")
    total = sum(gas for gas, _ in rows.values())
    return total, {
        "vectors": len(rows),
        "totalGas": total,
        "precompileTotalGas": sum(precompile for _, precompile in rows.values()),
    }


def write_score(
    track_name: str,
    artifact_path: Path,
    csv_path: Path,
    score_path: Path,
    summary_path: Path,
    vectors_path: Path,
) -> None:
    track = track_config(track_name)
    _, artifact = read_artifact(artifact_path)
    expected, suite_hash = read_vectors(vectors_path)
    try:
        if track.framed:
            score, metrics = parse_framed_csv(csv_path, expected)
        else:
            score, metrics = parse_modexp_csv(csv_path, expected)
    except OSError as error:
        raise ValueError(f"could not read scorer output {csv_path}: {error}") from error

    metrics = {
        "verified": True,
        "bytecodeBytes": len(artifact) // 2,
        "vectorSuiteSha256": suite_hash,
        **metrics,
    }
    atomic_write(
        score_path,
        json.dumps({"score": score, "metrics": metrics}, indent=2) + "\n",
    )

    summary = (
        f"## EIP-8200 {track.display_name} benchmark\n\n"
        f"- Verified gas score: **{score:,}**\n"
        f"- Bytecode size: **{len(artifact) // 2:,} bytes**\n"
        f"- Correctness vectors: **{len(expected)}/{len(expected)}**\n"
        f"- Vector suite SHA-256: `{suite_hash}`\n"
        "- Lean Comparator: **accepted**\n"
    )
    atomic_write(summary_path, summary)


def usage() -> str:
    return (
        "usage:\n"
        "  yukon_benchmark.py prepare TRACK SUBMITTED_HEX TRUSTED_HEX "
        "ARTIFACT_MODULE CHALLENGE\n"
        "  yukon_benchmark.py score TRACK TRUSTED_HEX SCORER_CSV SCORE_JSON SUMMARY VECTORS"
    )


def main() -> None:
    try:
        command = sys.argv[1]
        arguments = sys.argv[2:]
    except IndexError:
        raise SystemExit(usage()) from None

    try:
        if command == "prepare" and len(arguments) == 5:
            track_name, *paths = arguments
            prepare(track_name, *(Path(argument) for argument in paths))
        elif command == "score" and len(arguments) == 6:
            track_name, *paths = arguments
            write_score(track_name, *(Path(argument) for argument in paths))
        else:
            raise SystemExit(usage())
    except (ValueError, OSError, KeyError, TypeError) as error:
        raise SystemExit(str(error)) from error


if __name__ == "__main__":
    main()
